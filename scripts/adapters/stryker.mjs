// Mutation adapter for StrykerJS. It wraps the package's own Stryker config,
// narrows `mutate` to the lines the item changed, and asks for a JSON report.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { shellQuote } from '../lib/util.mjs';

const RUNNER_PLUGIN = fileURLToPath(new URL('./stryker-jest-per-file.mjs', import.meta.url));
const BASE_NAMES = ['stryker.config.mjs', 'stryker.config.js', 'stryker.config.cjs', 'stryker.config.json', 'stryker.conf.mjs', 'stryker.conf.js', 'stryker.conf.cjs', 'stryker.conf.json'];

export function findBaseConfig(pkgRoot) {
  return BASE_NAMES.map((n) => path.join(pkgRoot, n)).find((p) => fs.existsSync(p)) ?? null;
}

export function configSource({ basePath, mutate, report, options }) {
  const jest = options.runner === 'jest';
  return `// Generated by gated-pipeline for one mutation run. Do not edit.
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';

const basePath = ${JSON.stringify(basePath)};
let base = {};
if (basePath) {
  base = basePath.endsWith('.json')
    ? JSON.parse(fs.readFileSync(basePath, 'utf8'))
    : ((await import(pathToFileURL(basePath).href)).default ?? {});
}

export default {
  ...base,
  mutate: ${JSON.stringify(mutate)},
  reporters: ['json'],
  jsonReporter: { fileName: ${JSON.stringify(report)} },
  incremental: false,
${options.concurrency ? `  concurrency: ${Number(options.concurrency)},\n` : ''}${
    jest
      ? `  testRunner: 'gated-jest',
  coverageAnalysis: 'perTest',
  plugins: [...(base.plugins ?? ['@stryker-mutator/*']), ${JSON.stringify(RUNNER_PLUGIN)}],\n`
      : ''
  }};
`;
}

// -> { command, env, report } for one package. `ranges` are { file, start, end } inside the package.
export function prepare({ pkg, pkgRoot, stateDir, ranges, tag = '' }) {
  const options = pkg.mutation;
  const report = path.join(stateDir, `mutation-${pkg.name}${tag}.json`);
  const config = path.join(stateDir, `stryker-${pkg.name}${tag}.config.mjs`);
  const map = path.join(stateDir, `jest-map-${pkg.name}${tag}.json`);
  fs.rmSync(report, { force: true });
  fs.rmSync(map, { force: true });
  fs.writeFileSync(
    config,
    configSource({
      basePath: findBaseConfig(pkgRoot),
      mutate: ranges.map((r) => `${r.file}:${r.start}-${r.end}`),
      report,
      options,
    }),
  );
  return {
    command: `${options.command ?? 'npx stryker run'} ${shellQuote(config)}`,
    env: { GATED_JEST_MAP: map, GATED_JEST_STATIC: options.staticTests === 'all' ? 'all' : 'related' },
    report,
  };
}
